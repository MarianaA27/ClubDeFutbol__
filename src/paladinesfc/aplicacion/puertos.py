"""
Puertos (interfaces) que la capa de aplicación necesita de la infraestructura.

Los servicios dependen de estos protocolos, no de pyodbc ni de SQL Server. Así
se pueden probar con implementaciones en memoria y la infraestructura puede
cambiar sin tocar las reglas de negocio (inversión de dependencias).
"""
from __future__ import annotations

from typing import Protocol

from paladinesfc.dominio.jugador import Jugador
from paladinesfc.dominio.profesor import Profesor
from paladinesfc.dominio.tutor import Tutor
from paladinesfc.dominio.vinculo import TutoresDelJugador, VinculoTutor


class RepositorioJugadores(Protocol):
    def obtener(self, id_jugador: int) -> Jugador | None: ...
    def existe_documento(self, documento: str, excluir_id: int | None = None) -> bool: ...
    def listar_con_tutor_principal(self, documento: str | None = None) -> list[dict]: ...
    def agregar(self, jugador: Jugador) -> int: ...
    def actualizar(self, jugador: Jugador) -> None: ...
    def contar_plantillas_activas(self, id_jugador: int) -> int: ...
    def plantillas_activas(self, id_jugador: int) -> list[dict]: ...


class RepositorioTutores(Protocol):
    def obtener(self, id_tutor: int) -> Tutor | None: ...
    def existe_documento(self, documento: str, excluir_id: int | None = None) -> bool: ...
    def existe_telefono(self, telefono: str, excluir_id: int | None = None) -> bool: ...
    def listar(self, documento: str | None = None, solo_activos: bool = False) -> list[Tutor]: ...
    def agregar(self, tutor: Tutor) -> int: ...
    def actualizar(self, tutor: Tutor) -> None: ...
    def contar_jugadores_activos(self, id_tutor: int) -> int: ...
    def jugadores_a_cargo(self, id_tutor: int) -> list[dict]: ...


class RepositorioProfesores(Protocol):
    def obtener(self, id_profesor: int) -> Profesor | None: ...
    def existe_documento(self, documento: str, excluir_id: int | None = None) -> bool: ...
    def existe_telefono(self, telefono: str, excluir_id: int | None = None) -> bool: ...
    def listar(self, documento: str | None = None, solo_activos: bool = False) -> list[Profesor]: ...
    def agregar(self, profesor: Profesor) -> int: ...
    def actualizar(self, profesor: Profesor) -> None: ...
    def plantillas_a_cargo(self, id_profesor: int) -> list[dict]: ...


class RepositorioVinculos(Protocol):
    def de_jugador(self, id_jugador: int) -> TutoresDelJugador: ...
    def de_vinculo(self, id_jugador_tutor: int) -> TutoresDelJugador | None: ...
    def agregar(self, vinculo: VinculoTutor) -> int: ...
    def establecer_principal(self, id_jugador: int, id_tutor: int) -> None: ...
    def eliminar(self, id_jugador_tutor: int) -> None: ...


class UnidadDeTrabajo(Protocol):
    """Una transacción por operación de negocio (ADR-0002)."""
    jugadores: RepositorioJugadores
    tutores: RepositorioTutores
    profesores: RepositorioProfesores
    vinculos: RepositorioVinculos

    def __enter__(self) -> "UnidadDeTrabajo": ...
    def __exit__(self, tipo, excepcion, traza) -> bool: ...
    def commit(self) -> None: ...
